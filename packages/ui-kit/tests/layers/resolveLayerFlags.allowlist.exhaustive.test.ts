function collectEnabledFlags(search: string): readonly LayerId[] {
  const resolved = resolveLayerFlags({ search, isDevelopment: true });
  return resolved.enabledLayerIds;
}

for (const testCase of ALLOWLIST_EXHAUSTIVE_CASES) {
  test(`allowlist exhaustive direct ${testCase.name}`, () => {
    const resolved = resolveLayerFlags({
      search: testCase.search,
      isDevelopment: true,
    });

    assert.equal(resolved.source, "layers");
    assert.equal(resolved.layersDirective, "allowlist");
    assert.deepEqual(resolved.enabledLayerIds, [...testCase.expectedEnabled]);
    assert.equal(resolved.unknownLayerIds.length, 0);
    assert.equal(resolved.knownRequestedLayerIds.length, testCase.expectedEnabled.length);

    for (const canonicalId of CANON_LAYER_IDS) {
      const expected = testCase.expectedEnabled.includes(canonicalId);
      assert.equal(resolved.flags[canonicalId], expected);
    }
  });

  test(`allowlist exhaustive precedence ${testCase.name}`, () => {
    const withProfile = resolveLayerFlags({
      search: `${testCase.search}&layerProfile=perf`,
      isDevelopment: true,
    });

    assert.equal(withProfile.source, "layers");
    assert.equal(withProfile.profile, "neutral");
    assert.deepEqual(withProfile.enabledLayerIds, [...testCase.expectedEnabled]);
  });

  test(`allowlist exhaustive determinism ${testCase.name}`, () => {
    const snapshots = new Set<string>();
    for (let i = 0; i < 8; i += 1) {
      const resolved = resolveLayerFlags({ search: testCase.search, isDevelopment: true });
      snapshots.add(createStableResolvedSnapshot(resolved));
    }
    assert.equal(snapshots.size, 1);
  });
}

test("allowlist exhaustive helper parity", () => {
  assert.deepEqual(collectEnabledFlags("?layers=stage.noise,card.blur"), ["stage.noise", "card.blur"]);
  assert.deepEqual(collectEnabledFlags("?layers=none"), []);
});

