export function listPresetGalleryByStyle(styleId: LuxuryStyleId, limit = 40): readonly LuxuryPreset[] {
  return PRESET_GALLERY.filter((entry) => entry.preset.styleId === styleId)
    .slice(0, limit)
    .map((entry) => entry.preset);
}

export function listSurfaceRecipesForStyle(
  styleId: LuxuryStyleId,
  surfaceId?: SurfaceId,
  limit = 48
): readonly {
  readonly id: string;
  readonly styleId: LuxuryStyleId;
  readonly surfaceId: SurfaceId;
  readonly materialId: string;
  readonly blurStrengthPx: number;
  readonly grainOpacity: number;
  readonly gridOpacity: number;
  readonly specularIntensity: number;
  readonly note: string;
}[] {
  const filtered = SURFACE_RECIPE_CATALOG.filter(
    (entry) => entry.styleId === styleId && (!surfaceId || entry.surfaceId === surfaceId)
  );
  return filtered.slice(0, limit);
}

