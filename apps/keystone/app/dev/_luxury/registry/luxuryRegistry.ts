function clampNumber(value: number, min: number, max: number): number {
  if (!Number.isFinite(value)) {
    return min;
  }

  if (value < min) {
    return min;
  }

  if (value > max) {
    return max;
  }

  return value;
}

function ensureSurfaceId(surfaceId: SurfaceId): SurfaceId {
  if (LUXURY_SURFACE_IDS.includes(surfaceId)) {
    return surfaceId;
  }

  return "pitchCard";
}

export function listLuxuryStyles(): readonly LuxuryStyleDefinition[] {
  return LUXURY_STYLE_IDS.map((id) => STYLE_MAP[id]);
}

export function resolveLuxuryStyle(styleId: LuxuryStyleId): LuxuryStyleDefinition {
  return STYLE_MAP[styleId];
}

export function listLuxuryMaterials(
  styleId: LuxuryStyleId,
  options?: { readonly includeAlienTech?: boolean }
): readonly LuxuryMaterialDefinition[] {
  const includeAlienTech = options?.includeAlienTech ?? false;
  return MATERIALS.filter((item) => {
    if (item.styleId !== styleId) {
      return false;
    }

    if (!includeAlienTech && item.maturity === "Alien Tech") {
      return false;
    }

    return true;
  });
}

export function hasMaterialId(styleId: LuxuryStyleId, materialId: string): boolean {
  return MATERIALS.some((item) => item.styleId === styleId && item.id === materialId);
}

export function resolveLuxuryMaterial(
  styleId: LuxuryStyleId,
  materialId: string,
  options?: { readonly includeAlienTech?: boolean }
): LuxuryMaterialDefinition {
  const includeAlienTech = options?.includeAlienTech ?? false;
  const scoped = listLuxuryMaterials(styleId, { includeAlienTech });
  const direct = scoped.find((item) => item.id === materialId);
  if (direct) {
    return direct;
  }

  const fallback = scoped[0] ?? MATERIALS.find((item) => item.styleId === styleId) ?? MATERIALS[0];
  if (!fallback) {
    throw new Error(`No materials registered for style ${styleId}.`);
  }

  return fallback;
}

export function clampKnobsByProfile(knobs: VisualKnobs, perfProfile: PerfProfile): VisualKnobs {
  const blurMax =
    perfProfile === "perf" ? VISUAL_BOUNDS.blurStrengthPx.perfMax : VISUAL_BOUNDS.blurStrengthPx.max;
  const grainMax =
    perfProfile === "perf" ? VISUAL_BOUNDS.grainOpacity.perfMax : VISUAL_BOUNDS.grainOpacity.max;
  const gridMax =
    perfProfile === "perf" ? VISUAL_BOUNDS.gridOpacity.perfMax : VISUAL_BOUNDS.gridOpacity.max;
  const specularMax =
    perfProfile === "perf"
      ? VISUAL_BOUNDS.specularIntensity.perfMax
      : VISUAL_BOUNDS.specularIntensity.max;

  return {
    blurStrengthPx: clampNumber(
      knobs.blurStrengthPx,
      VISUAL_BOUNDS.blurStrengthPx.min,
      blurMax
    ),
    grainOpacity: clampNumber(knobs.grainOpacity, VISUAL_BOUNDS.grainOpacity.min, grainMax),
    gridOpacity: clampNumber(knobs.gridOpacity, VISUAL_BOUNDS.gridOpacity.min, gridMax),
    specularIntensity: clampNumber(
      knobs.specularIntensity,
      VISUAL_BOUNDS.specularIntensity.min,
      specularMax
    )
  };
}

export function createDefaultPreset(styleId: LuxuryStyleId): LuxuryPreset {
  const style = resolveLuxuryStyle(styleId);
  const base: LuxuryPreset = {
    version: 1,
    styleId,
    surfaceId: ensureSurfaceId(style.defaultSurfaceId),
    materialId: style.defaultMaterialId,
    perfProfile: "default",
    motionLevel: "standard",
    knobs: {
      blurStrengthPx: 10,
      grainOpacity: 0.16,
      gridOpacity: 0.18,
      specularIntensity: 0.56
    }
  };

  return {
    ...base,
    knobs: clampKnobsByProfile(base.knobs, base.perfProfile)
  };
}

export function repairPreset(
  preset: LuxuryPreset,
  options?: { readonly includeAlienTech?: boolean }
): LuxuryPreset {
  const includeAlienTech = options?.includeAlienTech ?? false;
  const style = resolveLuxuryStyle(preset.styleId);
  const materials = listLuxuryMaterials(preset.styleId, { includeAlienTech });
  const materialId =
    materials.find((item) => item.id === preset.materialId)?.id ?? style.defaultMaterialId;
  const surfaceId = ensureSurfaceId(preset.surfaceId);
  const knobs = clampKnobsByProfile(preset.knobs, preset.perfProfile);

  return {
    ...preset,
    surfaceId,
    materialId,
    knobs
  };
}

