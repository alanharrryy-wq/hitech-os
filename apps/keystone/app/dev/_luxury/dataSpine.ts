interface JsonProviderStore {
  readonly byId: ReadonlyMap<string, KpiPreviewPayload>;
  readonly issues: readonly string[];
}

function tableRowsFromColumns(columns: readonly string[]): readonly Record<string, string | number>[] {
  const rowA: Record<string, string | number> = {};
  const rowB: Record<string, string | number> = {};
  const rowC: Record<string, string | number> = {};

  columns.forEach((column, index) => {
    rowA[column] = index % 2 === 0 ? `${column}-A` : index * 7 + 11;
    rowB[column] = index % 2 === 0 ? `${column}-B` : index * 5 + 9;
    rowC[column] = index % 2 === 0 ? `${column}-C` : index * 4 + 4;
  });

  return [rowA, rowB, rowC];
}

function widgetToPreview(widget: WidgetConfig): KpiPreviewPayload {
  switch (widget.kind) {
    case "stat":
      return {
        shape: "single-value",
        title: widget.title,
        value: widget.config.value,
        unit: widget.config.unit,
        delta:
          widget.config.trend === "up"
            ? 4.5
            : widget.config.trend === "down"
              ? -3.5
              : 0,
        points: widget.config.sparkline
      };
    case "table":
      return {
        shape: "table",
        title: widget.title,
        columns: widget.config.columns.map((column) => column.label),
        rows: tableRowsFromColumns(widget.config.columns.map((column) => column.label))
      };
    case "feed":
      return {
        shape: "events",
        title: widget.title,
        events: [
          { at: "09:10", text: `${widget.config.source} event imported`, severity: "info" },
          { at: "09:22", text: `${widget.config.source} threshold warning`, severity: "warn" },
          { at: "09:30", text: `${widget.config.source} action required`, severity: "critical" }
        ]
      };
    case "dial-placeholder":
      return {
        shape: "ratio",
        title: widget.title,
        value: widget.config.value,
        unit: widget.config.unit,
        numerator: widget.config.value,
        denominator: widget.config.max,
        delta: widget.config.warningThreshold !== null ? -2.1 : 1.2
      };
    case "chart-placeholder":
      return {
        shape: "timeseries",
        title: widget.title,
        points: widget.config.seriesNames.map((_, index) => 40 + index * 8),
        labels: widget.config.seriesNames
      };
    default:
      // Exhaustiveness guard: keep a resilient fallback for future widget kinds.
      void widget;
      return {
        shape: "single-value",
        title: "Untitled KPI",
        value: 0,
        unit: ""
      };
  }
}

function parseJsonProvider(): JsonProviderStore {
  try {
    const parsed = JSON.parse(KPI_JSON_PROVIDER_SOURCE) as unknown;
    const validated = validateCatalogSnapshot(parsed);
    const byId = new Map<string, KpiPreviewPayload>();
    validated.value.items.forEach((item) => byId.set(item.id, item.preview));
    return {
      byId,
      issues: validated.issues.map((entry) => `${entry.path}: ${entry.message}`)
    };
  } catch (error) {
    return {
      byId: new Map<string, KpiPreviewPayload>(),
      issues: [error instanceof Error ? error.message : "JSON provider parse failure"]
    };
  }
}

const JSON_PROVIDER = parseJsonProvider();

export interface KpiDataSpineResult {
  readonly payload: KpiPreviewPayload | null;
  readonly source: "mock" | "json" | "http" | "http-fallback";
  readonly isLoading: boolean;
  readonly errorMessage: string | null;
}

// Data Spine adapter that normalizes mock/json/http into one preview payload shape.
export function useKpiDataSpine(input: {
  readonly provider: DataProviderId;
  readonly item: KpiCatalogItem | null;
}): KpiDataSpineResult {
  const httpQuery = useQuery<WidgetsQueryResponse>({
    queryKey: ["keystone", "dev", "kpi-supermarket", "widgets"],
    enabled: input.provider === "http",
    queryFn: () =>
      fetchContract({
        path: "/api/widgets",
        schema: WidgetsQueryResponseSchema,
        resource: "api.widgets"
      })
  });

  return useMemo(() => {
    const selectedItem = input.item;

    if (!selectedItem) {
      return {
        payload: null,
        source: "mock",
        isLoading: false,
        errorMessage: null
      };
    }

    if (input.provider === "mock") {
      return {
        payload: selectedItem.previewMock,
        source: "mock",
        isLoading: false,
        errorMessage: null
      };
    }

    if (input.provider === "json") {
      const payload = JSON_PROVIDER.byId.get(selectedItem.id) ?? selectedItem.previewMock;
      return {
        payload,
        source: "json",
        isLoading: false,
        errorMessage: JSON_PROVIDER.issues.length > 0 ? JSON_PROVIDER.issues.join("; ") : null
      };
    }

    if (httpQuery.isLoading || httpQuery.isFetching) {
      return {
        payload: null,
        source: "http",
        isLoading: true,
        errorMessage: null
      };
    }

    if (!httpQuery.data) {
      return {
        payload: selectedItem.previewMock,
        source: "http-fallback",
        isLoading: false,
        errorMessage:
          httpQuery.error instanceof Error
            ? httpQuery.error.message
            : "HTTP provider unavailable. Mock fallback applied."
      };
    }

    const widget = httpQuery.data.widgets.find((entry) => entry.id === selectedItem.widgetId);
    if (!widget) {
      return {
        payload: selectedItem.previewMock,
        source: "http-fallback",
        isLoading: false,
        errorMessage: `Widget ${selectedItem.widgetId} not found in /api/widgets response.`
      };
    }

    return {
      payload: widgetToPreview(widget),
      source: "http",
      isLoading: false,
      errorMessage: null
    };
  }, [httpQuery.data, httpQuery.error, httpQuery.isFetching, httpQuery.isLoading, input.item, input.provider]);
}

