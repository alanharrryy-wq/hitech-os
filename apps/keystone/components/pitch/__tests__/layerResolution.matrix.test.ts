describe('layer resolution matrix', () => {
  it('validates every layer query combination deterministically', () => {
    for (const item of cases) {
      const result = resolveLayerFlags(item.searchParams);

      expect(result.mode, item.id).toBe(item.expectedMode);
      expect(result.profile, item.id).toBe(item.expectedProfile);
      expect(result.debug, item.id).toBe(item.expectedDebug);

      for (const layer of item.expectedOn) {
        expect(result.flags[layer as keyof typeof result.flags], `${item.id}:${layer}:on`).toBe(true);
      }

      for (const layer of item.expectedOff) {
        expect(result.flags[layer as keyof typeof result.flags], `${item.id}:${layer}:off`).toBe(false);
      }

      expect(result.queryEcho.layerProfile).toBe(item.expectedProfile);
      expect(result.queryEcho.debug).toBe(item.expectedDebug ? "1" : "0");
    }
  });

  it('exercises matrix cardinality assumptions', () => {
    expect(cases.length).toBeGreaterThan(250);
    expect(cases[0]?.id).toBe("case-0001");
    expect(cases[cases.length - 1]?.id).toBeDefined();
  });
});

