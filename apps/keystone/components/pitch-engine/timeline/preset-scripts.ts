import type { TimelinePresetScript, TimelineTrackType, TimelineValuePoint } from "../types";

const TRACKS: TimelineTrackType[] = [
  "camera",
  "overlay",
  "motion",
  "layers",
  "lighting",
  "subtitle",
  "audio",
  "annotation"
];

function values(input: {
  readonly opacity: number;
  readonly x: number;
  readonly y: number;
  readonly scale: number;
  readonly visible: boolean;
}): TimelineValuePoint[] {
  return [
    { key: "opacity", value: input.opacity },
    { key: "x", value: input.x },
    { key: "y", value: input.y },
    { key: "scale", value: input.scale },
    { key: "visible", value: input.visible }
  ];
}

function buildPreset(input: {
  readonly id: string;
  readonly label: string;
  readonly style: TimelinePresetScript["style"];
  readonly description: string;
  readonly durationMs: number;
  readonly motionFactor: number;
  readonly cameraBias: number;
  readonly overlayBias: number;
}): TimelinePresetScript {
  const markers = [
    {
      type: "Reveal" as const,
      t: Math.round(input.durationMs * 0.2),
      label: "Reveal",
      note: "Reveal marker generated by preset script"
    },
    {
      type: "Settle" as const,
      t: Math.round(input.durationMs * 0.55),
      label: "Settle",
      note: "Settle marker generated by preset script"
    },
    {
      type: "CTA" as const,
      t: Math.round(input.durationMs * 0.82),
      label: "CTA",
      note: "CTA marker generated by preset script"
    }
  ];

  const tracks = TRACKS.map((kind, trackIndex) => {
    const kindFactor = trackIndex + 1;
    const baseX = kind === "camera" ? input.cameraBias : input.overlayBias;

    return {
      kind,
      label: `${kind.toUpperCase()} Track`,
      enabled: true,
      keyframes: [
        {
          t: 0,
          easing: "ease-in" as const,
          values: values({
            opacity: 0,
            x: baseX,
            y: kindFactor * 4,
            scale: 0.92,
            visible: false
          })
        },
        {
          t: Math.round(input.durationMs * 0.25),
          easing: "ease-out" as const,
          values: values({
            opacity: 0.75,
            x: baseX + 14,
            y: kindFactor * 7,
            scale: 1,
            visible: true
          })
        },
        {
          t: Math.round(input.durationMs * 0.5),
          easing: "linear" as const,
          values: values({
            opacity: 1,
            x: baseX + Math.round(24 * input.motionFactor),
            y: kindFactor * 8,
            scale: 1.03,
            visible: true
          })
        },
        {
          t: Math.round(input.durationMs * 0.76),
          easing: "ease-in-out" as const,
          values: values({
            opacity: 1,
            x: baseX + Math.round(31 * input.motionFactor),
            y: kindFactor * 9,
            scale: 1.05,
            visible: true
          })
        },
        {
          t: input.durationMs,
          easing: "ease-out" as const,
          values: values({
            opacity: 1,
            x: baseX + Math.round(38 * input.motionFactor),
            y: kindFactor * 10,
            scale: 1.08,
            visible: true
          })
        }
      ]
    };
  });

  return {
    id: input.id,
    label: input.label,
    style: input.style,
    description: input.description,
    durationMs: input.durationMs,
    markers,
    tracks
  };
}

