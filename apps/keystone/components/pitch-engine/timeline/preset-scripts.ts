export const TIMELINE_PRESET_SCRIPTS: TimelinePresetScript[] = cinematicCatalog.map((preset) =>
  buildPreset(preset)
);

export function findPresetById(presetId: string): TimelinePresetScript | null {
  for (const preset of TIMELINE_PRESET_SCRIPTS) {
    if (preset.id === presetId) {
      return preset;
    }
  }

  return null;
}

export function ensurePreset(presetId: string): TimelinePresetScript {
  const preset = findPresetById(presetId);
  if (preset) {
    return preset;
  }

  return TIMELINE_PRESET_SCRIPTS[0];
}
